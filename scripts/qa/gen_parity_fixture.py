#!/usr/bin/env python3
"""Generate the deterministic LocalDb parity seed from assets/app/db/apps.db.

The app ships `assets/app/db/apps.db` with `apps`, `category`, and `config`
tables.  The parity harness must exercise the real Dart Floor DAO and the real
Rust `LocalDbDriver` against the *same* seed, so this script:

1. reads the shipped asset read-only and validates its integrity/schema;
2. exports every `apps` row (ordered by appId), every `category` row (ordered by
   id), and the latest `config` row into `test/fixtures/parity/localdb.sql`.
   The asset has no `readme`/`extra` columns (the shipped DB predates those
   Floor fields), so the export adds them as NULL - the same values the Dart
   Floor mapper and the Rust driver observe on a fresh install;
3. creates the Dart-compatible `config(version, proxy)` table and the FTS5 index
   exactly as `AppInfoDatabase._setupFts5` does at runtime;
4. applies the SQL to `test/fixtures/parity/localdb.db` with the `sqlite3` CLI
   and verifies the result.

Running it twice produces byte-identical SQL and DB files, which is why
`scripts/qa/parity.sh` can rebuild the fixture on every run without a dirty
worktree.  Output is intentionally independent of row order in the asset: all
reads use explicit ORDER BY.

Usage:
    python3 scripts/qa/gen_parity_fixture.py \
        --asset assets/app/db/apps.db \
        --sql test/fixtures/parity/localdb.sql \
        --db test/fixtures/parity/localdb.db
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sqlite3
import subprocess
import sys
from pathlib import Path
from typing import NoReturn

REQUIRED_ASSET_TABLES = {"apps", "category", "config"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asset", default="assets/app/db/apps.db")
    parser.add_argument("--sql", default="test/fixtures/parity/localdb.sql")
    parser.add_argument("--db", default="test/fixtures/parity/localdb.db")
    return parser.parse_args()


def quote(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def fail(message: str) -> NoReturn:
    print(f"gen_parity_fixture: {message}", file=sys.stderr)
    raise SystemExit(1)


def read_asset(path: Path) -> tuple[list[tuple], list[tuple], tuple]:
    if not path.is_file():
        fail(f"seed asset not found: {path}")
    uri = f"{path.resolve().as_uri()}?mode=ro"
    try:
        conn = sqlite3.connect(uri, uri=True)
    except sqlite3.Error as error:
        fail(f"cannot open seed asset {path}: {error}")
    try:
        integrity = conn.execute("PRAGMA integrity_check").fetchone()
        if not integrity or integrity[0] != "ok":
            fail(f"seed asset {path} failed integrity_check: {integrity!r}")
        tables = {
            row[0]
            for row in conn.execute(
                "SELECT name FROM sqlite_master WHERE type='table'"
            )
        }
        missing = REQUIRED_ASSET_TABLES - tables
        if missing:
            fail(f"seed asset {path} is missing tables: {sorted(missing)}")

        apps = conn.execute(
            "SELECT appId, name, user, repositories, icon, des, category "
            "FROM apps ORDER BY appId"
        ).fetchall()
        categories = conn.execute(
            "SELECT id, description, icon FROM category ORDER BY id"
        ).fetchall()
        config = conn.execute(
            "SELECT version FROM config ORDER BY rowid DESC LIMIT 1"
        ).fetchone()
        if not apps:
            fail(f"seed asset {path} has no apps rows")
        if not categories:
            fail(f"seed asset {path} has no category rows")
        if config is None:
            fail(f"seed asset {path} has no config row")
        return apps, categories, config
    except sqlite3.DatabaseError as error:
        fail(f"seed asset {path} is not a readable SQLite database: {error}")
    finally:
        conn.close()


def build_sql(
    asset: Path, asset_sha: str, apps: list[tuple], categories: list[tuple], config: tuple
) -> str:
    lines = [
        "-- Generated by scripts/qa/gen_parity_fixture.py - DO NOT EDIT BY HAND.",
        f"-- source_asset: {asset.as_posix()}",
        f"-- source_asset_sha256: {asset_sha}",
        "-- extraction:",
        "--   apps:     SELECT appId,name,user,repositories,icon,des,category",
        "--             FROM apps ORDER BY appId",
        "--   category: SELECT id,description,icon FROM category ORDER BY id",
        "--   config:   SELECT version FROM config ORDER BY rowid DESC LIMIT 1",
        f"-- rows exported: apps={len(apps)} category={len(categories)} config=1",
        "--",
        "-- The shipped asset predates Floor's readme/extra fields; both are NULL",
        "-- in the seed so Dart and Rust read the same columns and values.",
        "",
        "DROP TABLE IF EXISTS apps;",
        "DROP TABLE IF EXISTS category;",
        "DROP TABLE IF EXISTS config;",
        "DROP TABLE IF EXISTS apps_fts;",
        "",
        "CREATE TABLE apps (",
        "  appId TEXT PRIMARY KEY,",
        "  name TEXT NOT NULL,",
        "  user TEXT,",
        "  repositories TEXT,",
        "  icon TEXT,",
        "  des TEXT,",
        "  readme TEXT,",
        "  category TEXT,",
        "  extra TEXT",
        ");",
        "",
        "CREATE TABLE category (",
        "  id TEXT PRIMARY KEY,",
        "  description TEXT NOT NULL,",
        "  icon TEXT NOT NULL",
        ");",
        "",
        "-- Dart getVersion() selects version and proxy from this table.",
        "CREATE TABLE config (",
        "  version TEXT PRIMARY KEY,",
        "  proxy TEXT",
        ");",
        "",
    ]
    for app_id, name, user, repositories, icon, des, category in apps:
        lines.append(
            "INSERT INTO apps "
            "(appId, name, user, repositories, icon, des, readme, category, extra) "
            f"VALUES ({quote(app_id)}, {quote(name)}, {quote(user)}, "
            f"{quote(repositories)}, {quote(icon)}, {quote(des)}, NULL, "
            f"{quote(category)}, NULL);"
        )
    lines.append("")
    for cat_id, description, icon in categories:
        lines.append(
            "INSERT INTO category (id, description, icon) "
            f"VALUES ({quote(cat_id)}, {quote(description)}, {quote(icon)});"
        )
    version = config[0]
    lines.extend(
        [
            "",
            f"INSERT INTO config (version, proxy) VALUES ({quote(version)}, NULL);",
            "",
            "-- Mirror AppInfoDatabase._setupFts5 (contentless FTS + triggers).",
            "CREATE VIRTUAL TABLE apps_fts USING fts5(",
            "  appId UNINDEXED,",
            "  name,",
            "  des,",
            "  content=''",
            ");",
            "CREATE TRIGGER apps_fts_insert AFTER INSERT ON apps BEGIN",
            "  INSERT INTO apps_fts(rowid, appId, name, des)",
            "  VALUES (new.rowid, new.appId, new.name, new.des);",
            "END;",
            "CREATE TRIGGER apps_fts_delete AFTER DELETE ON apps BEGIN",
            "  DELETE FROM apps_fts WHERE rowid = old.rowid;",
            "END;",
            "CREATE TRIGGER apps_fts_update AFTER UPDATE ON apps BEGIN",
            "  DELETE FROM apps_fts WHERE rowid = old.rowid;",
            "  INSERT INTO apps_fts(rowid, appId, name, des)",
            "  VALUES (new.rowid, new.appId, new.name, new.des);",
            "END;",
            "INSERT INTO apps_fts(rowid, appId, name, des)",
            "  SELECT rowid, appId, name, des FROM apps ORDER BY rowid;",
            "",
            "-- Floor opens version 1 without running onCreate.",
            "PRAGMA user_version = 1;",
            "",
        ]
    )
    return "\n".join(lines)


def apply_sql(sql_path: Path, db_path: Path) -> None:
    db_path.parent.mkdir(parents=True, exist_ok=True)
    for suffix in ("", "-wal", "-shm", "-journal"):
        candidate = Path(str(db_path) + suffix)
        if candidate.exists():
            candidate.unlink()
    try:
        with sql_path.open("rb") as handle:
            subprocess.run(
                ["sqlite3", str(db_path)],
                stdin=handle,
                check=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
    except FileNotFoundError:
        fail("sqlite3 CLI not found (required by scripts/qa/parity.sh)")
    except subprocess.CalledProcessError as error:
        detail = error.stderr.decode("utf-8", "replace").strip()
        fail(f"sqlite3 failed to build {db_path}: {detail}")
    _verify(db_path)


def _verify(db_path: Path) -> None:
    try:
        conn = sqlite3.connect(f"{db_path.resolve().as_uri()}?mode=ro", uri=True)
    except sqlite3.Error as error:
        fail(f"cannot open generated seed {db_path}: {error}")
    try:
        integrity = conn.execute("PRAGMA integrity_check").fetchone()
        if not integrity or integrity[0] != "ok":
            fail(f"generated seed {db_path} failed integrity_check: {integrity!r}")
        apps = conn.execute("SELECT count(*) FROM apps").fetchone()[0]
        categories = conn.execute("SELECT count(*) FROM category").fetchone()[0]
        config = conn.execute("SELECT count(*) FROM config").fetchone()[0]
        fts = conn.execute("SELECT count(*) FROM apps_fts").fetchone()[0]
        version = conn.execute("PRAGMA user_version").fetchone()[0]
        if apps == 0:
            fail(f"generated seed {db_path} has no apps rows")
        if categories == 0:
            fail(f"generated seed {db_path} has no category rows")
        if config != 1:
            fail(f"generated seed {db_path} must have exactly one config row")
        if fts != apps:
            fail(
                f"generated seed {db_path} FTS rows ({fts}) != apps rows ({apps})"
            )
        if version != 1:
            fail(f"generated seed {db_path} user_version={version}, expected 1")
        print(
            "seed OK: "
            f"apps={apps} categories={categories} config={config} "
            f"fts={fts} user_version={version}"
        )
    finally:
        conn.close()


def main() -> int:
    args = parse_args()
    asset = Path(args.asset)
    sql_path = Path(args.sql)
    db_path = Path(args.db)

    raw = asset.read_bytes() if asset.is_file() else b""
    asset_sha = hashlib.sha256(raw).hexdigest()

    apps, categories, config = read_asset(asset)
    sql = build_sql(asset, asset_sha, apps, categories, config)
    sql_path.parent.mkdir(parents=True, exist_ok=True)
    if not sql_path.exists() or sql_path.read_text(encoding="utf-8") != sql:
        sql_path.write_text(sql, encoding="utf-8")
    apply_sql(sql_path, db_path)
    db_sha = hashlib.sha256(db_path.read_bytes()).hexdigest()
    print(f"asset sha256: {asset_sha}")
    print(f"sql:  {sql_path} ({len(sql.encode('utf-8'))} bytes)")
    print(f"db:   {db_path} ({db_path.stat().st_size} bytes) sha256={db_sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
